namespace TicTacToe.Models.Enums;

/// <summary>
/// Contains the game options in the main menu.
/// </summary>
internal enum GameOption
{
    /// <summary>
    /// Represents an option to play Tic Tac Toe.
    /// </summary>
    TicTacToe = 1,

    /// <summary>
    /// Represents an option to play Snake Water Gun.
    /// </summary>
    SnakeWaterGun = 2,

    /// <summary>
    /// Represents an option to view and update the profile information.
    /// </summary>
    Profile = 3,

    /// <summary>
    /// Represents an option to logout.
    /// </summary>
    LogOut = 4,
}
